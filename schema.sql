-- Sharenest — Supabase schema
-- Run this in: Supabase Dashboard > SQL Editor > New query > Run

create table if not exists public.requests (
  id bigint generated by default as identity primary key,
  title text not null,
  category text,
  description text,
  duration text,
  date_label text,
  location text,
  fee text,
  group_name text,
  emoji text,
  community text,
  created_by text,
  avatar text,
  color text,
  status text default 'Open',
  offers integer default 0,
  created_at timestamptz default now()
);

-- Row Level Security
alter table public.requests enable row level security;

-- DEMO policies: anyone (even logged-out visitors) can read and create requests.
-- This matches the current prototype, which has no real authentication yet.
-- Tighten these once you add Supabase Auth (e.g. restrict insert/update to
-- authenticated users, and scope rows to a community_id / user_id).

create policy "Public can read requests"
  on public.requests for select
  using (true);

create policy "Public can create requests"
  on public.requests for insert
  with check (true);

